#!/usr/bin/env bash
# Writes scripts/platform-tools.txt: the MCP tool names the platform serves,
# one per line, read from the `name: "..."` lines of the platform's
# src/mcp/server.ts at a given ref. CI's tool-names job checks the plugin
# against that pinned copy, so it never needs the platform repository.
#
# Re-run it at each resync of the plugin with the platform, then commit the
# result with the skill changes it goes with:
#   bash scripts/platform-tools.sh <platform checkout> [ref]   (ref: default HEAD, e.g. v0.16.3)
set -euo pipefail

platform="${1:-}"
ref="${2:-HEAD}"
if [ -z "$platform" ] || [ ! -d "$platform" ]; then
  echo "usage: bash scripts/platform-tools.sh <platform checkout> [ref]" >&2
  exit 2
fi

here="$(cd "$(dirname "$0")" && pwd)"
out="$here/platform-tools.txt"
source_file="src/mcp/server.ts"

if ! commit="$(git -C "$platform" rev-parse --verify --quiet --end-of-options "$ref^{commit}")"; then
  echo "platform-tools: $ref is not a commit in $platform" >&2
  exit 2
fi
if ! server="$(git -C "$platform" show "$commit:$source_file")"; then
  echo "platform-tools: $source_file is not readable at $ref" >&2
  exit 2
fi
described="$(git -C "$platform" describe --tags --match 'v*' "$commit" 2>/dev/null || echo "$commit")"

# A tool's own entry is the only `name:` line that holds nothing but a
# snake_case string. That rules out the server's own name, which sits inside
# an object literal on one line and has a hyphen.
names="$(printf '%s\n' "$server" \
  | grep -E '^[[:space:]]+name: "[a-z][a-z0-9]*(_[a-z0-9]+)+",[[:space:]]*$' \
  | sed -E 's/^[[:space:]]+name: "([a-z0-9_]+)",[[:space:]]*$/\1/' \
  | LC_ALL=C sort)" || true

count="$(printf '%s\n' "$names" | grep -c . || true)"
if [ "$count" -eq 0 ]; then
  echo "platform-tools: no tool names found in $source_file at $ref" >&2
  exit 1
fi
if dupes="$(printf '%s\n' "$names" | uniq -d | grep .)"; then
  echo "platform-tools: a tool name appears twice in $source_file at $ref:" >&2
  printf '  %s\n' $dupes >&2
  exit 1
fi

{
  echo "# The platform's MCP tool names, one per line: $count tools at $described"
  echo "# (commit $commit), from the name: lines of $source_file."
  echo "# Generated by scripts/platform-tools.sh; do not edit by hand. Refresh at each"
  echo "# resync with: bash scripts/platform-tools.sh <platform checkout> <release tag>"
  printf '%s\n' "$names"
} >"$out"
echo "platform-tools: wrote $count names at $described to ${out#"$PWD"/}"
